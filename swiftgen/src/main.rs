// Generates Swift wrappers for every backend RPC, using the same service and
// method indices upstream's Python and TypeScript bindings use.
//
//     swiftgen <descriptors.bin> <output.swift>

use std::collections::HashMap;
use std::fmt::Write;
use std::{env, fs};

use anki_proto_gen::{get_services, BackendService, Method};
use anyhow::{bail, Context, Result};
use prost_reflect::{DescriptorPool, MessageDescriptor};

fn main() -> Result<()> {
    let args: Vec<String> = env::args().collect();
    let [_, descriptors, output] = args.as_slice() else {
        bail!("usage: swiftgen <descriptors.bin> <output.swift>");
    };
    let bytes = fs::read(descriptors).with_context(|| format!("reading {descriptors}"))?;
    let pool = DescriptorPool::decode(bytes.as_slice())?;
    let (_, services) = get_services(&pool);

    let mut out = String::from(
        "// GENERATED by swiftgen from anki/proto. Do not edit.\n\n\
         import Foundation\n\
         import SwiftProtobuf\n\n\
         extension AnkiBackend {\n",
    );
    let names = method_names(&services);
    for service in &services {
        writeln!(out, "\n    // MARK: {}\n", service.name)?;
        for method in service.all_methods() {
            render_method(service, method, &names[&(service.index, method.index)], &mut out)?;
        }
    }
    out.push_str("}\n");

    if fs::read_to_string(output).ok().as_deref() != Some(out.as_str()) {
        fs::write(output, out).with_context(|| format!("writing {output}"))?;
    }
    Ok(())
}

/// Swift method name for each (service, method). proto_gen gives snake_case
/// names (`get_deck_tree`), which become `getDeckTree`. RPC names are unique within
/// a service but not across them, so clashes get the service name prepended.
fn method_names(services: &[BackendService]) -> HashMap<(usize, usize), String> {
    let mut counts: HashMap<String, usize> = HashMap::new();
    for service in services {
        for method in service.all_methods() {
            *counts.entry(lower_camel(&method.name)).or_default() += 1;
        }
    }
    let mut names = HashMap::new();
    for service in services {
        let prefix = lower_camel(
            service
                .name
                .trim_start_matches("Backend")
                .trim_end_matches("Service"),
        );
        for method in service.all_methods() {
            let base = lower_camel(&method.name);
            let name = if counts[&base] > 1 {
                format!("{prefix}{}", upper_camel(&method.name))
            } else {
                base
            };
            names.insert((service.index, method.index), name);
        }
    }
    names
}

fn render_method(service: &BackendService, method: &Method, name: &str, out: &mut String) -> Result<()> {
    if let Some(comments) = &method.comments {
        for line in comments.lines() {
            writeln!(out, "    /// {}", line.trim())?;
        }
    }
    let input = method.proto.input();
    let output = method.proto.output();
    let (svc, idx) = (service.index, method.index);
    let call = if is_empty(&input) {
        format!("run(service: {svc}, method: {idx}, input: Anki_Generic_Empty())")
    } else {
        format!("run(service: {svc}, method: {idx}, input: input)")
    };
    let params = if is_empty(&input) {
        String::new()
    } else {
        format!("_ input: {}", swift_type(&input))
    };
    if is_empty(&output) {
        writeln!(out, "    public func {name}({params}) throws {{\n        _ = try {call}\n    }}\n")?;
    } else {
        let ty = swift_type(&output);
        writeln!(
            out,
            "    @discardableResult\n    public func {name}({params}) throws -> {ty} {{\n        try {ty}(serializedBytes: {call})\n    }}\n"
        )?;
    }
    Ok(())
}

fn is_empty(message: &MessageDescriptor) -> bool {
    message.full_name() == "anki.generic.Empty"
}

/// swift-protobuf naming: package `anki.deck_config` + message `Foo.Bar`
/// becomes `Anki_DeckConfig_Foo.Bar`.
fn swift_type(message: &MessageDescriptor) -> String {
    let package = message.package_name();
    let nested = &message.full_name()[package.len() + 1..];
    let prefix: Vec<String> = package.split('.').map(upper_camel).collect();
    format!("{}_{}", prefix.join("_"), nested)
}

fn upper_camel(s: &str) -> String {
    s.split('_')
        .map(|part| {
            let mut chars = part.chars();
            chars
                .next()
                .map(|c| c.to_uppercase().chain(chars).collect::<String>())
                .unwrap_or_default()
        })
        .collect()
}

fn lower_camel(s: &str) -> String {
    let camel = upper_camel(s);
    let mut chars = camel.chars();
    chars
        .next()
        .map(|c| c.to_lowercase().chain(chars).collect::<String>())
        .unwrap_or_default()
}
